import { NextResponse } from 'next/server';
import { requireAdmin } from '@/lib/adminAuth';

export async function POST(req: Request) {
    const authError = await requireAdmin();
    if (authError) return authError;

    try {
        const { scrapedData } = await req.json();

        const systemPrompt = `
Ти си главен редактор в луксозна туристическа агенция "Beliva VIP".
Получаваш сурови данни от друга агенция. Задачата ти е да ги ПРЕФОРМУЛИРАШ със собствени думи в професионален VIP стил.

КРИТИЧНИ ПРАВИЛА ЗА ЗАПАЗВАНЕ НА СМИСЪЛА:
1. НИКОГА не променяй факти: дати, цени, брой нощувки, имена на хотели, градове, забележителности, полети, часове.
2. За "includes" и "excludes": всяка точка от оригинала ТРЯБВА да присъства в резултата. Не пропускай НИЩО, не добавяй нищо ново. Само преформулирай всяка точка с различни думи, запазвайки точния смисъл. Например: "Самолетен билет София-Токио-София" → "Двупосочен полет по маршрут София – Токио – София".
3. За "program": запази ВСИЧКИ дни и ВСИЧКИ събития/места от всеки ден. Пренапиши описанията увлекателно, но не изпускай нито една активност, хранене или детайл.
4. Пиши на книжовен български, без правописни грешки.

ВЪРНИ СТРОГ JSON ОБЕКТ СЪС СЛЕДНАТА СТРУКТУРА:
{
  "title": "Стилно заглавие (напр. 'Магията на Перу: Мачу Пикчу и Лима')",
  "intro": "2-3 изречения, впечатляващ абзац за дестинацията, който да въвлече читателя да закупи тура. Не е резюме на програмата, а отделен, емоционален текст (2-4 изречения) в VIP стил, който рисува атмосферата/впечатленията на дестинацията, без да повтаря факти от програмата. Напр. 'Стъпете на земята на цъфтящите вишни в момент, в който Цио се разбужда в хилядите си цветове — пътуване, в което древната традиция среща неоноваващата се технология.'",
  "country": ["Перу"], // Масив от стрингове (само държавите на български)
  "price": "Остави само числото и символа на валутата (напр. '5500 €'). ВИНАГИ използвай символ, а не код: EUR → €, USD → $, GBP → £. НИКОГА не пиши 'EUR'.",
  "days": 10, // Число
  "nights": 9, // Число
  "route": "Маршрутът кратко",
  "program": [
    { "day": 1, "title": "22.08.26 Кратко заглавие на деня", "description": "Подробно и увлекателно описание С ВСИЧКИ факти от оригинала, НО БЕЗ датата — тя е само в title" }
  ],
  // ЗА "title" НА ВСЕКИ ДЕН: Започни с датата във формат DD.MM.YY. ВСЕКИ ден в суровия текст започва с дата (напр. "2 ДЕН -29.11.2026") —
  // ИЗВЛЕЧИ датата на ВСЕКИ отделен ден от неговия сегмент и я сложи в title на СЪОТВЕТНИЯ ден. НЕ само на първия!
  // Пример за цялата програма: ден 1 → "27.11.26 Полет София – Пунта Кана", ден 2 → "28.11.26 Свободен ден на плажа", ден 3 → "29.11.26 Екскурзия Adventure Park".
  // Ако за конкретен ден в оригинала НЯМА дата — само заглавието, без измислена дата.
  // В "description" НИКОГА не повтаряй датата и не започвай с "1 ден", "Ден 1" и т.н.
  "includes": ["Двупосочен полет...", "Нощувки..."], // ВСЯКА точка от оригинала, преформулирана
  "excludes": ["Бакшиши..."], // ВСЯКА точка от оригинала, преформулирана
  "docs": ["Международен паспорт..."], // Масив от стрингове
  "info": ["Условия за плащане..."] // Масив от стрингове
}
Ако някоя информация липсва в суровия текст, остави празен масив или празен стринг. ИЗКЛЮЧЕНИЕ: "intro" ВИНАГИ трябва да има съдържание — ако оригиналният текст няма готово интро, съчини го сам на база на държавата/маршрута. НЕ ИЗПОЛЗВАЙ Markdown (\`\`\`json), върни само чист JSON!
`;

        const response = await fetch('https://api.openai.com/v1/chat/completions', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${process.env.OPENAI_API_KEY}`
            },
            body: JSON.stringify({
                model: "gpt-4o",
                response_format: { type: "json_object" }, // Принуждава GPT да върне 100% валиден JSON
                // Изричен, висок max_tokens — без това моделът разчита на вътрешен default, който за големи,
                // много-дестинационни турове може да не стига за пълната, детайлна програма (причина
                // моделът да съкрати отговора по-рано, отколкото дене от програмата са кратки).
                max_tokens: 8000,
                messages: [
                    { role: "system", content: systemPrompt },
                    { role: "user", content: JSON.stringify(scrapedData) }
                ],
                temperature: 0.7
            })
        });

        const gptData = await response.json();
        
        if (gptData.error) {
            throw new Error(gptData.error.message);
        }

        const formattedTour = JSON.parse(gptData.choices[0].message.content);
        return NextResponse.json({ success: true, tour: formattedTour });

    } catch (error: any) {
        return NextResponse.json({ error: error.message }, { status: 500 });
    }
}