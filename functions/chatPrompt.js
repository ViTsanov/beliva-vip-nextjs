const MAX_MESSAGE_CHARS = 600;
const MAX_HISTORY_MESSAGES = 6; // колкото праща AIChatWidget
const MAX_HISTORY_CHARS = 2000; // отговорите на асистента съдържат дълги линкове

// Историята идва от браузъра и може да е подправена: само ролите на разговора (иначе някой може да подаде
// свои „system“ инструкции), последните няколко реплики и с ограничена дължина.
function sanitizeHistory(history) {
    if (!Array.isArray(history)) return [];
    return history
        .filter((m) => m && (m.role === "user" || m.role === "assistant") && typeof m.content === "string" && m.content.trim())
        .slice(-MAX_HISTORY_MESSAGES)
        .map((m) => ({ role: m.role, content: m.content.slice(0, MAX_HISTORY_CHARS) }));
}

